-- [C] PROBES
--
-- Three entries in the requirements catalog were marked "needs confirmation":
-- the query shape that reaches them was derived by reading the code, not by
-- running it.  T01 resolves them.  These probes print the plan so the answer
-- is recorded in the expected output rather than in someone's memory.
--

-- [C] FR-92: does a childless Result node with a non-empty relids set actually
-- appear, and does it emit a "Replaces" property naming the relation?
-- show_result_replacement_info() returns early when plan.lefttree is non-NULL,
-- so a gating Result (One-Time Filter) is not enough; the scan or the aggregate
-- itself has to have been replaced.
-- ANSWER: confirmed.  Three distinct forms, and they differ in whether a name
-- follows the replacement type -- all three must be covered by T15.
SET constraint_exclusion = on;

SELECT 'FR-92 probe: scan replacement -> Replaces carries a RELATION NAME' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM zsec_excluded WHERE zsec_k < 0');

SELECT 'FR-92 probe: join replacement -> Replaces carries ALIASES' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM zsec_excluded zsec_ja JOIN zsec_excluded zsec_jb USING (zsec_k) WHERE zsec_ja.zsec_k < 0');

RESET constraint_exclusion;

SELECT 'FR-92 probe: MinMax replacement -> Replaces carries NO name' AS probe;
SELECT * FROM zsec_plan('SELECT min(zsec_bal) FROM zsec_customers');

-- Contrast: a contradictory qual on a column with no supporting CHECK
-- constraint is NOT proven empty, and constraint_exclusion defaults to
-- "partition" (which only applies to partitions and inheritance children), so
-- neither of those alone produces a replacement.  Recorded so the two
-- preconditions are documented rather than rediscovered.
SELECT 'FR-92 probe: contradictory qual, no constraint, default GUC (control)' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM zsec_customers WHERE zsec_ssn IS NULL AND zsec_ssn IS NOT NULL');

-- [C] FR-13a: which statement drives refname through the alias/fallback path
-- rather than through get_rel_name()?
--
-- ANSWER: the SELECT, not the INSERT.  Scanning a partitioned parent emits
-- BOTH names on one line -- the partition child as the object name and the
-- parent as the reference name -- so a single scan node discloses two
-- identifiers and T15 has to redact both.  The INSERT takes the ordinary
-- nominal-relation path and discloses only the parent.
SELECT 'FR-13a probe: INSERT into partitioned parent (ordinary path)' AS probe;
SELECT * FROM zsec_plan('INSERT INTO zsec_parted VALUES (1, ''x'')');

SELECT 'FR-13a probe: SELECT from partitioned parent (child + parent, one line)' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM zsec_parted WHERE zsec_k = 1');

-- [C] FR-90 second seed: the subquery-alias seed at allpaths.c reaches
-- subroot->plan_name, but a subquery in FROM becomes a SubqueryScan (or is
-- flattened away entirely), not a SubPlan.  Does the alias surface as a
-- Subplan Name at all?
--
-- ANSWER: no.  Flattened, the alias vanishes completely; un-flattened, it
-- appears as a Subquery Scan alias -- which is FR-13's territory, not FR-90's.
-- No "Subplan Name" is produced either way.  The requirements catalog entry for
-- this seed should be narrowed to say the seed reaches subroot->plan_name but
-- not EXPLAIN output.  FR-90's CTE seed (above) remains confirmed.
SELECT 'FR-90 probe: subquery alias seed, flattened -> alias vanishes' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM (SELECT count(*) FROM zsec_customers) AS zsec_alias');

SELECT 'FR-90 probe: subquery alias seed, un-flattenable -> Subquery Scan alias, no Subplan Name' AS probe;
SELECT * FROM zsec_plan('SELECT * FROM (SELECT zsec_ssn, count(*) FROM zsec_customers GROUP BY zsec_ssn OFFSET 0) AS zsec_alias2 WHERE zsec_alias2.zsec_ssn = ''x''');

