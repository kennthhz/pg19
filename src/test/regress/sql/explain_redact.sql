--
-- MARKING DISCIPLINE
--
-- The detector only works if every object in the fixture schema actually
-- carries the marker.  Marking them by hand and eyeballing it is not a
-- guarantee: one unmarked column is a permanent blind spot that no later test
-- would ever report, because the thing it would have caught is invisible to the
-- grep.
--
-- So the convention is enforced rather than trusted.  This query returns any
-- object in the schema whose name is not marked; it must return nothing.
-- Adding an unmarked fixture object is then a test failure at the moment of
-- writing, not a silent hole discovered years later.
--
-- Placed after the LAST object is created.  Run earlier -- as the first draft
-- was, before zsec_fixtures existed -- and anything created afterwards is
-- unchecked by construction, which makes the stated invariant false.
--
-- The pattern allows a leading underscore because PostgreSQL names the array
-- type of "zsec_foo" as "_zsec_foo".
--
SELECT kind, name FROM (
    SELECT 'relation' AS kind, c.relname::text AS name
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'zsec_ns'
    UNION ALL
    -- Sequences and indexes are excluded, with cause.  A sequence relation has
    -- three fixed internal columns (last_value, log_cnt, is_called) chosen by
    -- PostgreSQL, not by us, and they cannot carry user information.  Index
    -- column names either mirror the underlying table's columns -- already
    -- covered by this same query -- or are generated for expression indexes.
    -- Everything else with columns is in scope.
    SELECT 'column', a.attname::text
      FROM pg_attribute a
      JOIN pg_class c ON c.oid = a.attrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'zsec_ns' AND a.attnum > 0 AND NOT a.attisdropped
       AND c.relkind NOT IN ('S', 'i')
    UNION ALL
    SELECT 'function', p.proname::text
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'zsec_ns'
    UNION ALL
    SELECT 'type', t.typname::text
      FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
     WHERE n.nspname = 'zsec_ns'
    UNION ALL
    SELECT 'collation', cl.collname::text
      FROM pg_collation cl JOIN pg_namespace n ON n.oid = cl.collnamespace
     WHERE n.nspname = 'zsec_ns'
    UNION ALL
    SELECT 'constraint', con.conname::text
      FROM pg_constraint con JOIN pg_namespace n ON n.oid = con.connamespace
     WHERE n.nspname = 'zsec_ns'
    UNION ALL
    -- Function argument names are the one catalog the fixture set depends on
    -- that the first draft of this query missed: FR-94's named-argument label
    -- was marked by hand and enforced by nothing.
    SELECT 'argument name', unnest(p.proargnames)::text
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'zsec_ns' AND p.proargnames IS NOT NULL
    UNION ALL
    SELECT 'enum label', e.enumlabel::text
      FROM pg_enum e
      JOIN pg_type t ON t.oid = e.enumtypid
      JOIN pg_namespace n ON n.oid = t.typnamespace
     WHERE n.nspname = 'zsec_ns'
) obj
 WHERE name !~ '^_?zsec_'
 -- COLLATE "C" on every text sort in this file: the suite runs under whatever
 -- locale the build host has, and a linguistic collation orders these rows
 -- differently from C.  pg_upgrade's test harness initialises its cluster with a
 -- different locale than "make check" does, so without this the same tree
 -- produces two different expected outputs.
 ORDER BY kind COLLATE "C", name COLLATE "C";

-- Same idea for the seeded data: every stored value must carry the marker, or a
-- leaked value would be invisible to the detector.  Must return nothing.
SELECT 'unmarked value' AS problem, v
  FROM (
    SELECT zsec_ssn AS v FROM zsec_customers
    UNION ALL SELECT (zsec_comp).zsec_fld_ssn FROM zsec_customers
    UNION ALL SELECT (zsec_comp).zsec_fld_name FROM zsec_customers
    UNION ALL SELECT zsec_kind::text FROM zsec_customers
  ) vals
 WHERE v IS NOT NULL AND v !~ '^zsec'
 ORDER BY v COLLATE "C";

