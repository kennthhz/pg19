CREATE FUNCTION zsec_func(zsec_arg text) RETURNS boolean
    LANGUAGE plpgsql VOLATILE AS $$ BEGIN RETURN true; END $$;

-- Marked DATA, not just marked schema.
--
-- The detector greps for the marker, which catches leaked *identifiers*.  It is
-- blind to leaked *values* -- a real SSN in a Filter clause is not an identifier
-- and matches nothing.  Rather than build a classifier that recognises
-- arbitrary sensitive data, the values are made self-identifying too: every
-- stored value carries the same marker, so a leaked value is exactly as
-- detectable as a leaked name, by the same one-line grep.
--
-- Seeding also fixes a plain gap: with empty tables, ANALYZE-mode records report
-- zero rows everywhere, plan shapes that need real data never occur, and the
-- cardinality behaviour in requirements section 9 cannot be exercised at all.
--
-- ANALYZE is run explicitly afterwards.  Without it reltuples stays stale and
-- autovacuum may or may not update it mid-run, which would make plan choice --
-- and therefore the expected output -- nondeterministic.
INSERT INTO zsec_customers (zsec_ssn, zsec_bal, zsec_when, zsec_comp, zsec_kind)
