--
-- FORMAT COVERAGE
--
-- Standing criterion 2 requires every fixture to be clean in all four formats,
-- but every fixture above runs text only.  The property that makes the
-- single-format run defensible is that the markers survive each format's
-- escaping unchanged -- "zsec_" and "zsecdata-" contain no character that
-- escape_json, the XML escaper or escape_yaml touches, and no format wraps long
-- lines, so an identifier is never split across a boundary.  That is load-
-- bearing and nothing pinned it, so pin it here: the same query must yield the
-- same identifier set in all four formats.
--
SELECT format_name,
       CASE WHEN found = (SELECT array_agg(l ORDER BY l COLLATE "C")
                            FROM zsec_leaks('SELECT zsec_a.zsec_id FROM zsec_customers zsec_a WHERE zsec_a.zsec_ssn = ''zsec_val_secret''',
                                            'COSTS OFF') AS l)
            THEN 'same as text'
            ELSE 'DIFFERS: ' || array_to_string(found, ' ') END AS verdict
  FROM (VALUES ('text'), ('json'), ('xml'), ('yaml')) AS fmt(format_name),
       LATERAL (SELECT array_agg(l ORDER BY l COLLATE "C") AS found
                  FROM zsec_leaks('SELECT zsec_a.zsec_id FROM zsec_customers zsec_a WHERE zsec_a.zsec_ssn = ''zsec_val_secret''',
                                  'COSTS OFF, FORMAT ' || fmt.format_name) AS l) g
 ORDER BY format_name;

--
-- NEGATIVE CONTROL, established by T01: an UPDATE of a composite subfield never
-- prints the field name.  The requirements proposed this as an FR-93 fixture;
-- no shape reaches a field-name emission site through an assignment -- not with
-- a column source, not with RETURNING.  The field name reaches output through a
-- READ, which the "composite field select" and "whole-row field reference"
-- fixtures already cover.
--
-- Retained as an assertion rather than deleted, so that if a future version
-- starts printing the target field name it fails here instead of shipping
-- silently.
--
SELECT count(*) AS assignment_must_not_print_field_name
  FROM zsec_leaks('UPDATE zsec_customers SET zsec_comp.zsec_fld_ssn = ''x''',
                  'COSTS OFF, VERBOSE') AS l
 WHERE l = 'zsec_fld_ssn';

--
-- NEGATIVE CONTROL, established by T01: a named-argument label never reaches a
-- plan.  The parser resolves named notation to positional order and discards the
-- NamedArgExpr wrapper, so "zsec_func(zsec_arg => zsec_ssn)" deparses as
-- "zsec_func(zsec_ssn)".  Verified with arguments given OUT OF ORDER, which is
-- the case that forces the parser to reorder and so had the best chance of
-- preserving the labels -- it does not.
--
-- ruleutils.c's T_NamedArgExpr branch therefore serves raw parse trees, such as
-- a stored default expression printed by pg_get_expr(), not plan trees.  FR-94
-- is a guard for a path EXPLAIN cannot currently reach, like FR-98c.
--
-- Pinned rather than dropped, so that if named arguments ever start surviving
-- into plans this fails instead of shipping silently.
--
SELECT count(*) AS named_arg_label_must_not_reach_a_plan
  FROM zsec_leaks('SELECT zsec_id FROM zsec_customers WHERE zsec_func(zsec_arg => zsec_ssn)',
                  'COSTS OFF') AS l
 WHERE l = 'zsec_arg';

