       ROW('zsecdata-fld-' || i, 'zsecdata-name-' || i)::zsec_composite,
       (CASE WHEN i % 2 = 0 THEN 'zsec_val_a' ELSE 'zsec_val_b' END)::zsec_enum
  FROM generate_series(1, 20) AS i;

