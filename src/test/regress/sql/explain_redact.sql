SELECT count(*) AS must_be_zero
  FROM zsec_leaks('SELECT 1', 'COSTS OFF');

-- "timestamp with time zone" contains "zone".  This is the false positive that
-- a bare /z[a-z_]+/ detector would report, and the reason the marker prefix is
-- four characters long.
SELECT count(*) AS must_be_zero_time_zone_is_not_a_leak
  FROM zsec_leaks('SELECT now() AT TIME ZONE ''UTC''', 'COSTS OFF');

--
-- NEGATIVE CONTROL, established by T01: a VALUES range-table entry discloses
-- nothing, because its user-written alias and column aliases do not survive
-- into the plan.  EXPLAIN prints the planner's internal "*VALUES*" name and
-- column1..columnN instead.  This holds in every shape tried: bare, wrapped in
-- an un-flattenable subquery, LATERAL, and INSERT ... VALUES.
--
-- Pinned as a test rather than deleted: if a future version starts propagating
-- the user's alias into the plan, this assertion fails and a new leak path gets
-- noticed instead of shipping silently.
--
SELECT count(*) AS values_alias_must_not_leak
  FROM zsec_leaks('SELECT * FROM (VALUES (1,2),(3,4)) AS zsec_v(zsec_v1, zsec_v2) WHERE zsec_v1 > 0',
                    'COSTS OFF, VERBOSE');

-- Column aliases written on a VALUES clause DO reach output when the VALUES is
-- wrapped in a subquery that survives flattening -- but as the *subquery's*
-- column names, which the "subquery output name + alias" fixture already
-- covers.  Recorded so the distinction is documented.
SELECT count(l) > 0 AS values_aliases_leak_via_enclosing_subquery
  FROM zsec_leaks('SELECT * FROM (SELECT * FROM (VALUES (1,2),(3,4)) AS zsec_v(zsec_v1,zsec_v2) OFFSET 0) zsec_w WHERE zsec_w.zsec_v1 > 0',
                    'COSTS OFF, VERBOSE') AS l;

