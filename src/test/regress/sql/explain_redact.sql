--
-- The detector.
--
-- Returns one row per distinct fixture identifier found in the EXPLAIN output
-- of the given query.  An empty result means "no leak".  Reporting the
-- identifiers rather than a bare boolean is what makes a failure diagnosable.
--
-- Matching on a substring rather than a whole identifier is intentional: it
-- catches a leak even when the name is embedded in a larger string, such as
-- inside a quoted literal (nextval('zsec_customers_zsec_id_seq')) or inside a
-- deparsed expression.
--
-- Passing an empty option list yields a bare "EXPLAIN <query>", because
-- "EXPLAIN () <query>" is a syntax error.  Once T04 lands, callers pass
-- 'REDACT' (or 'REDACT, VERBOSE', etc.) and the same assertions run inverted.
--
CREATE FUNCTION zsec_leaks(query_text text, explain_opts text)
RETURNS SETOF text
LANGUAGE plpgsql AS
$$
DECLARE
    ln  text;
    buf text := '';
    cmd text;
BEGIN
    IF explain_opts IS NULL OR explain_opts = '' THEN
        cmd := 'EXPLAIN ' || query_text;
    ELSE
        cmd := format('EXPLAIN (%s) %s', explain_opts, query_text);
    END IF;

    FOR ln IN EXECUTE cmd LOOP
        buf := buf || ln || E'\n';
    END LOOP;

    -- Two markers.  "zsec_" tags identifiers; "zsecdata-" tags stored values.
    -- Values need their own alternative because a leaked value is not an
    -- identifier, so an identifier-only pattern is structurally blind to the
    -- entire class of data leaks.
    --
    -- Case-insensitive ('gi'): a marked name or value routed through upper()
    -- arrives as ZSEC_CUSTOMERS and a case-sensitive pattern would read that as
    -- clean.  Harmless while the assertions are positive, exactly wrong once
    -- they invert from T04 onward.  Results are lower-cased so the expected
    -- identifier comparison stays exact.
    -- COLLATE "C" so the identifier order does not depend on the host locale.
    -- It matters even though the markers are pure ASCII: "zsec_ssn" and
    -- "zsecdata-ssn" first differ at "_" against "d", and a linguistic
    -- collation ignores punctuation at the primary level where C does not, so
    -- the two orderings disagree.
    --
    -- The sort is in an outer query rather than on the DISTINCT itself because
    -- ORDER BY on a SELECT DISTINCT has to name a select-list expression, and
    -- "ORDER BY 1 COLLATE \"C\"" does not mean the first column -- it parses as
    -- a collation applied to the integer 1, which fails at run time.
    RETURN QUERY
        SELECT ident
          FROM (SELECT DISTINCT lower(m[1]) AS ident
                  FROM regexp_matches(buf,
                                      '(zsec_[a-z0-9_]*|zsecdata-[a-z0-9-]*)',
                                      'gi') m) d
         ORDER BY ident COLLATE "C";
END
$$;

-- Plan printer for the [C] probes below.  Strips the details that vary between
-- machines so the expected output is stable, while keeping the property names
-- and identifiers that the probes exist to reveal.
CREATE FUNCTION zsec_plan(query_text text, explain_opts text DEFAULT 'COSTS OFF')
RETURNS SETOF text
LANGUAGE plpgsql AS
$$
DECLARE
    ln text;
BEGIN
    FOR ln IN EXECUTE format('EXPLAIN (%s) %s', explain_opts, query_text) LOOP
        CONTINUE WHEN ln ~ '^\s*(Buffers|Memory|Planning|Execution|JIT)';
        ln := regexp_replace(ln, '-?\m\d+\M', 'N', 'g');
        RETURN NEXT ln;
    END LOOP;
END
$$;

