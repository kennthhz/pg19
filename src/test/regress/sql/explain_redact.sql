-- ===========================================================================
-- T16: index names.
--
-- Four properties carry an index name and they are fed by three different code
-- paths, so each is checked separately rather than through one representative
-- fixture: Index Scan and Index Only Scan share ExplainIndexScanDetails(),
-- Bitmap Index Scan has its own inline emission in ExplainNode(), and
-- Conflict Arbiter Indexes is assembled in show_modifytable_info() and has never
-- gone through the shared function at all.  One fixture would leave two of the
-- three paths untested.
--
-- The guard for the first three went INWARD, into explain_get_index_name()
-- itself, which is the opposite direction from the one T14 took with
-- get_opclass_name().  That function has a caller -- pg_get_indexdef -- that must
-- never redact, so its guard had to be pushed OUT to its call sites; this one is
-- static and EXPLAIN-only, so a guard inside it covers every present and future
-- caller, and inside is also the only position from which the extension hook the
-- function consults can be skipped (FR-25).  The two are deliberately
-- inconsistent and someone will try to reconcile them.
--
-- The arbiter list still uses get_rel_name() in off mode -- it has never
-- consulted the hook, and routing it through the function would newly expose
-- unredacted arbiter names to an extension, which is a change to non-redacted
-- output and not this feature's to make -- and calls explain_redact_name()
-- directly under redaction.  That is what keeps it relatable to an Index Scan on
-- the same index (FR-40, below).
-- ===========================================================================
--
-- One verdict helper, because the same three clauses apply to all four surfaces:
-- the unredacted plan must name a real index (or the assertion is vacuous, which
-- is the failure T01 found in the original FR-16 fixture -- it got a Seq Scan and
-- passed), the redacted plan must carry no marker, and the redacted plan must
-- carry a pseudonym in the shape that surface prints.
CREATE FUNCTION zsec_index_verdict(query_text text, want_pattern text)
RETURNS text
LANGUAGE sql AS
$$
    SELECT CASE
             WHEN NOT EXISTS (SELECT 1 FROM zsec_plan(query_text, 'COSTS OFF') l
                               WHERE l LIKE '%zsec_idx_%')
               THEN 'FAIL: unredacted plan names no index -- assertion is vacuous'
             WHEN EXISTS (SELECT 1 FROM zsec_plan(query_text, 'COSTS OFF, REDACT') l
                           WHERE l LIKE '%zsec_%')
               THEN 'FAIL: marker present in redacted output'
             WHEN NOT EXISTS (SELECT 1 FROM zsec_plan(query_text, 'COSTS OFF, REDACT') l
                               WHERE l ~ want_pattern)
               THEN 'FAIL: no index pseudonym matching ' || want_pattern
             ELSE 'ok: ' || want_pattern
           END
$$;
