--
-- Every fixture must leak the identifier it names.  "FAIL" means either the
-- detector is broken or the fixture does not reach the path it claims to -- both
-- are T01 failures, and both must be resolved before any later task relies on
-- this harness.  The found list is printed on failure so the cause is visible
-- without re-running anything.
--
SELECT f.fr,
       f.note,
       CASE WHEN f.zsec_expect = ANY (g.found) THEN 'ok'
            ELSE 'FAIL: want ' || f.zsec_expect || ', got '
                 || coalesce(array_to_string(g.found, ' '), '(nothing)')
       END AS verdict
  FROM zsec_fixtures f
  CROSS JOIN LATERAL (SELECT array_agg(l ORDER BY l COLLATE "C") AS found
                        FROM zsec_leaks(f.qry, f.opts) AS l) g
 ORDER BY f.fr COLLATE "C", f.note COLLATE "C", f.qry COLLATE "C";

