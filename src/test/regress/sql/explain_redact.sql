--
-- EXPLAIN redaction — leak-detection harness and fixture schema
--
-- This file is task T01 of the auto-explain redaction plan.  It deliberately
-- contains NO product code and tests NO redaction behavior: at this point
-- EXPLAIN (REDACT) does not exist yet.
--
-- Its entire purpose is to build the leak detector and prove that it works,
-- by asserting that the detector FINDS the fixture identifiers in today's
-- ordinary, unredacted EXPLAIN output.  A detector that reported "clean"
-- because it was looking in the wrong place, or because its pattern never
-- matched, would silently pass every later task in the plan.  So the positive
-- control comes first, before there is anything to redact.
--
-- Every fixture object carries the marker prefix "zsec_".  The requirements
-- doc originally proposed a bare "z" prefix on the grounds that nothing in
-- core EXPLAIN output starts with z; that is not true -- "timestamp with time
-- zone" contains "zone", which a /z[a-z_]+/ detector reports as a leak.  The
-- four-character marker cannot collide with any English or SQL word appearing
-- in plan output, so the detector needs no word-boundary anchoring and has no
-- false positives.

